"""
Query Rewriter — переписывает запрос пользователя с учётом истории диалога.

Решает ТОЛЬКО проблему неявного контекста (местоимений, «выше», «в нем»).
НЕ добавляет новые фильтры (бренды, статусы, даты), которых не было в вопросе.
"""
from loguru import logger
from app.llm.vllm_client import vllm_client
from app.schemas import ChatHistoryItem


SYSTEM_PROMPT = """Ты — ассистент, который переписывает вопросы пользователя.
Твоя задача — сделать текущий вопрос понятным БЕЗ доступа к истории диалога.

ПРАВИЛА:
1. Замени все местоимения («он», «его», «этот», «там», «выше», «в данном») на конкретные сущности из истории.
2. Если в истории упоминался номер заказа (например, 98010227), а в текущем вопросе его нет, 
   но вопрос про заказ/товар/сумму/статус — ОБЯЗАТЕЛЬНО добавь этот номер заказа в вопрос.
3. 🔴 ЗАПРЕЩЕНО добавлять новые фильтры, которых НЕ БЫЛО в вопросе:
   - Не добавляй бренд (Евроопт, Хит, Грошык), если пользователь его не называл.
   - Не добавляй статус («На сайте», «Подтверждён», «Автоподтверждён»), если его не было.
   - Не добавляй период («за октябрь», «за сентябрь»), если его не было.
   - Не добавляй склад, регион, город.
   - НЕ ПРЕВРАЩАЙ «покажи заказы за октябрь» в «покажи заказы за октябрь Евроопт».
4. Не меняй смысл вопроса, не расширяй его, не сужай его.
5. Если вопрос уже понятен без истории — верни его БЕЗ изменений (буква в букву).
6. Верни ТОЛЬКО переписанный вопрос, без пояснений и кавычек.
"""


async def rewrite_query(query: str, history: list[ChatHistoryItem] | None) -> str:
    if not history:
        return query

    # Берем последние 4 сообщения (2 пары), чтобы не раздувать контекст
    recent = history[-4:]
    history_text = "\n".join(
        f"{'Пользователь' if m.role == 'user' else 'Ассистент'}: {m.content[:300]}"
        for m in recent
    )

    prompt = f"""ИСТОРИЯ ДИАЛОГА:
{history_text}

ТЕКУЩИЙ ВОПРОС:
{query}

Перепиши текущий вопрос, сделав его самостоятельным. Верни только текст вопроса."""

    try:
        rewritten = await vllm_client.generate_text(
            prompt=prompt,
            system=SYSTEM_PROMPT,
            max_tokens=150,
            temperature=0.0,
        )
        rewritten = rewritten.strip().strip('"').strip("'")
        
        if not rewritten:
            return query
            
        logger.info(f"[rewriter] было: {query!r} → стало: {rewritten!r}")
        return rewritten
    except Exception as e:
        logger.warning(f"[rewriter] ошибка переписывания: {e}")
        return query